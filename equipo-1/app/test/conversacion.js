const assert = require('node:assert/strict');
const fs = require('node:fs');
const engine = require('../engine');
const keys=['vecinos','alertas','confirmaciones','pedidos_confirmacion','anuncios','bitacora','media'];
const state=()=>Object.fromEntries(keys.map(k=>[k,[]]));
const d=state();
const alert=(type,description,gravity=2)=>({intencion:'alerta',alerta:{tipo:type,descripcion:description,gravedad:gravity}});
let r=engine.event(d,{phone:'ana',tipo_mensaje:'location',lat:-5.2,lng:-80.6,ia:{intencion:'registro'}});
assert.match(r.reply,/ubicación/i);
r=engine.event(d,{phone:'ana',tipo_mensaje:'text',ia:alert('sin_agua','No tengo agua')});
assert.equal(r.alerta.lat,-5.2);
r=engine.event(d,{phone:'ana',tipo_mensaje:'text',texto:'Hola',ia:{intencion:'registro'}});
assert.match(r.reply,/reporte anterior de sin agua/);
r=engine.event(d,{phone:'ana',tipo_mensaje:'text',ia:alert('inundacion','Se inunda la calle')});
assert.equal(d.alertas.length,2);assert.equal(r.alerta.tipo,'inundacion');
const other=engine.event(d,{phone:'luis',tipo_mensaje:'text',texto:'Hola',ia:{intencion:'registro'}});
assert.doesNotMatch(other.reply,/reporte anterior/);
assert.equal(engine.event(d,{phone:'ana',ia:{intencion:'consulta',respuesta_sugerida:'Puedes llamar al 116.'}}).reply,'Puedes llamar al 116.');
assert.match(engine.event(d,{phone:'otro',ia:{intencion:'confirmacion',confirmacion:'si'}}).reply,/solicitud/);
const urgent=engine.event(state(),{phone:'b',ia:alert('incendio','Hay un incendio',5)});
assert.equal(urgent.alerta.estado,'despachada');assert.match(urgent.reply,/No se ha contactado/);
const source=fs.readFileSync(require('node:path').join(__dirname,'../../n8n/preparar-evento.js'),'utf8');
const transform=new Function('$','$json',source);
const body={sender:{phone_number:'123',name:'Ana'},tipo_mensaje:'text',content:'Hola',lat:null,lng:null};
const result=transform(()=>({item:{json:{body}}}),{ia:alert('inundacion','Alerta anterior',5)});
assert.equal(result[0].json.ia.intencion,'registro');
console.log('Conversación: saludo, contexto, ubicación, incidentes separados, consulta, votos y urgencia correctos.');
